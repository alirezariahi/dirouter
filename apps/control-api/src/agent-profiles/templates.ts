/**
 * Ready-to-use configuration for coding agents (card 20.5). Every template points the tool at the
 * DiRouter gateway with one key and two models: `main` for the work and `fast` for background
 * tasks (titles, summaries, quick checks) where the tool supports it.
 *
 * Nothing replaces the user's own configuration: files go to `~/.config/dirouter/<profile>/`, and a
 * small launcher (`claude-dirouter`, `codex-dirouter`, …) starts the tool with them.
 */

export const AGENT_TOOLS = [
  'claude-code',
  'codex',
  'opencode',
  'gemini-cli',
  'aider',
  'env',
] as const;
export type AgentTool = (typeof AGENT_TOOLS)[number];

export interface ProfileInput {
  tool: AgentTool;
  /** Directory name under ~/.config/dirouter. */
  slug: string;
  gatewayUrl: string;
  /** The key, or a placeholder in previews. */
  apiKey: string;
  mainModel: string;
  fastModel: string;
  /** Claude Code: no telemetry, error reporting or update checks. */
  disableNonessentialTraffic?: boolean;
}

export interface GeneratedFile {
  /** Relative to the profile directory (~/.config/dirouter/<slug>/). */
  name: string;
  content: string;
  /** Makes the file a launcher installed into ~/.local/bin. */
  launcher?: string;
  description: string;
}

export const KEY_PLACEHOLDER = '<YOUR_DIROUTER_KEY>';

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;
const tomlString = (value: string) => JSON.stringify(value);
/** Single-quoted for a POSIX shell. */
const sh = (value: string) => `'${value.replace(/'/g, `'"'"'`)}'`;

function launcher(dir: string, command: string): string {
  return `#!/bin/sh\n# Generated by DiRouter.\nDIR="$HOME/.config/dirouter/${dir}"\n${command}\n`;
}

export function generateProfile(p: ProfileInput): GeneratedFile[] {
  const gw = p.gatewayUrl.replace(/\/+$/, '');
  switch (p.tool) {
    case 'claude-code': {
      const env: Record<string, string> = {
        ANTHROPIC_BASE_URL: gw,
        ANTHROPIC_AUTH_TOKEN: p.apiKey,
        ANTHROPIC_MODEL: p.mainModel,
        ANTHROPIC_DEFAULT_OPUS_MODEL: p.mainModel,
        ANTHROPIC_DEFAULT_SONNET_MODEL: p.mainModel,
        ANTHROPIC_DEFAULT_HAIKU_MODEL: p.fastModel,
        ANTHROPIC_SMALL_FAST_MODEL: p.fastModel,
        CLAUDE_CODE_SUBAGENT_MODEL: p.mainModel,
        ...(p.disableNonessentialTraffic ? { CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: '1' } : {}),
      };
      return [
        {
          name: 'claude-code.env',
          description: 'Gateway, key and a model per role (main; fast for background tasks).',
          content: `${Object.entries(env)
            .map(([k, v]) => `${k}=${sh(v)}`)
            .join('\n')}\n`,
        },
        {
          name: 'claude-code.json',
          description:
            'The same as Claude Code settings; to make DiRouter the default, merge its env block into ~/.claude/settings.json.',
          content: json({ env }),
        },
        {
          name: 'claude-dirouter',
          launcher: 'claude-dirouter',
          // Claude Code picks its endpoint from the process environment, so the launcher exports it.
          description: 'Starts Claude Code through DiRouter; your own ~/.claude stays as it is.',
          content: launcher(p.slug, 'set -a\n. "$DIR/claude-code.env"\nset +a\nexec claude "$@"'),
        },
      ];
    }
    case 'codex':
      return [
        {
          name: 'codex/config.toml',
          description:
            'Codex configuration in its own CODEX_HOME: the DiRouter provider and a `fast` profile.',
          content: [
            '# Generated by DiRouter.',
            `model = ${tomlString(p.mainModel)}`,
            'model_provider = "dirouter"',
            '',
            '[model_providers.dirouter]',
            'name = "DiRouter"',
            `base_url = ${tomlString(`${gw}/v1`)}`,
            'env_key = "DIROUTER_API_KEY"',
            'wire_api = "responses"',
            '',
            '[profiles.fast]',
            `model = ${tomlString(p.fastModel)}`,
            'model_provider = "dirouter"',
            '',
          ].join('\n'),
        },
        {
          name: 'codex-dirouter',
          launcher: 'codex-dirouter',
          description:
            'Starts Codex with this configuration (`codex-dirouter --profile fast` for the fast model).',
          content: launcher(
            p.slug,
            `CODEX_HOME="$DIR/codex" DIROUTER_API_KEY=${sh(p.apiKey)} exec codex "$@"`,
          ),
        },
      ];
    case 'opencode':
      return [
        {
          name: 'opencode.json',
          description: 'OpenCode configuration with DiRouter as an OpenAI-compatible provider.',
          content: json({
            $schema: 'https://opencode.ai/config.json',
            provider: {
              dirouter: {
                npm: '@ai-sdk/openai-compatible',
                name: 'DiRouter',
                options: { baseURL: `${gw}/v1`, apiKey: '{env:DIROUTER_API_KEY}' },
                models: Object.fromEntries(
                  [...new Set([p.mainModel, p.fastModel])].map((m) => [m, { name: m }]),
                ),
              },
            },
            model: `dirouter/${p.mainModel}`,
            small_model: `dirouter/${p.fastModel}`,
          }),
        },
        {
          name: 'opencode-dirouter',
          launcher: 'opencode-dirouter',
          description: 'Starts OpenCode with this configuration.',
          content: launcher(
            p.slug,
            `OPENCODE_CONFIG="$DIR/opencode.json" DIROUTER_API_KEY=${sh(p.apiKey)} exec opencode "$@"`,
          ),
        },
      ];
    case 'gemini-cli':
      return [
        {
          name: 'gemini-dirouter',
          launcher: 'gemini-dirouter',
          description: 'Starts Gemini CLI against the DiRouter Gemini endpoint.',
          content: launcher(
            p.slug,
            `GOOGLE_GEMINI_BASE_URL=${sh(gw)} GEMINI_API_KEY=${sh(p.apiKey)} GEMINI_MODEL=${sh(p.mainModel)} exec gemini "$@"`,
          ),
        },
      ];
    case 'aider':
      return [
        {
          name: 'aider.conf.yml',
          description: 'Aider configuration: main model, and the fast one as its weak model.',
          content: [
            '# Generated by DiRouter.',
            `openai-api-base: ${gw}/v1`,
            `openai-api-key: ${p.apiKey}`,
            `model: openai/${p.mainModel}`,
            `weak-model: openai/${p.fastModel}`,
            '',
          ].join('\n'),
        },
        {
          name: 'aider-dirouter',
          launcher: 'aider-dirouter',
          description: 'Starts Aider with this configuration.',
          content: launcher(p.slug, 'exec aider --config "$DIR/aider.conf.yml" "$@"'),
        },
      ];
    default:
      return [
        {
          name: 'dirouter.env',
          description: 'Environment variables for OpenAI- and Anthropic-compatible SDKs and tools.',
          content: [
            '# Generated by DiRouter. Load with: set -a; . ./dirouter.env; set +a',
            `OPENAI_BASE_URL=${gw}/v1`,
            `OPENAI_API_KEY=${p.apiKey}`,
            `ANTHROPIC_BASE_URL=${gw}`,
            `ANTHROPIC_AUTH_TOKEN=${p.apiKey}`,
            `DIROUTER_MODEL=${p.mainModel}`,
            `DIROUTER_FAST_MODEL=${p.fastModel}`,
            '',
          ].join('\n'),
        },
      ];
  }
}

/**
 * A POSIX shell script that writes the files (owner-only permissions, since they hold the key) and
 * installs the launchers into ~/.local/bin. It never touches the tool's own configuration.
 */
export function installScript(slug: string, files: GeneratedFile[]): string {
  const lines = [
    '#!/bin/sh',
    '# DiRouter agent profile installer. Writes to ~/.config/dirouter only, plus launchers in ~/.local/bin.',
    'set -eu',
    `DIR="$HOME/.config/dirouter/${slug}"`,
    'mkdir -p "$DIR" "$HOME/.local/bin"',
    'umask 077',
  ];
  files.forEach((file, i) => {
    const marker = `DIROUTER_EOF_${String(i)}`;
    if (file.name.includes('/'))
      lines.push(`mkdir -p "$DIR/${file.name.slice(0, file.name.lastIndexOf('/'))}"`);
    lines.push(`cat > "$DIR/${file.name}" <<'${marker}'`, file.content.replace(/\n$/, ''), marker);
    if (file.launcher)
      lines.push(
        `chmod 700 "$DIR/${file.name}"`,
        `ln -sf "$DIR/${file.name}" "$HOME/.local/bin/${file.launcher}"`,
      );
  });
  const launchers = files.filter((f) => f.launcher).map((f) => f.launcher);
  lines.push(
    `echo "DiRouter profile installed in $DIR"`,
    ...(launchers.length > 0
      ? [`echo "Run: ${launchers.join(', ')} (make sure ~/.local/bin is on your PATH)"`]
      : []),
    '',
  );
  return lines.join('\n');
}
